#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Tunakula — ONE-COMMAND staging publish on a Hostinger VPS.
#
# Run this ON THE VPS, from the repo root:
#     bash deploy/go-live-staging.sh
#
# It will: install Docker if missing, ask you for your three subdomains, generate a
# signing secret, write deploy/.env.staging, build + start the whole platform (database,
# API, both websites, Caddy with automatic HTTPS), wait until the API is healthy, and
# create your first Super Admin. At the end it prints your live URLs.
#
# Re-running it is safe: it reuses deploy/.env.staging if it already exists.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
cd "$(dirname "$0")/.."                                   # repo root
ENV_FILE="deploy/.env.staging"
COMPOSE="docker compose --env-file $ENV_FILE -f deploy/docker-compose.staging.yml"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
ask() { local p="$1" d="${2:-}" a; read -rp "$p${d:+ [$d]}: " a; echo "${a:-$d}"; }

# 1. Docker ------------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  say "Installing Docker…"
  curl -fsSL https://get.docker.com | sh
fi
docker compose version >/dev/null 2>&1 || { echo "Docker Compose plugin missing. Install it and re-run."; exit 1; }

# 2. Collect settings (only the first time) ----------------------------------
if [[ -f "$ENV_FILE" ]]; then
  say "Using existing $ENV_FILE"
else
  say "Let's set up your domains. Point each one's DNS A record at THIS server first."
  PUBLIC_IP="$(curl -fsS https://api.ipify.org 2>/dev/null || echo '<this-server-ip>')"
  echo "    This server's public IP appears to be: $PUBLIC_IP"
  BASE=$(ask "Your domain (e.g. tunakula.com)")
  API_DOMAIN=$(ask "  API subdomain"      "api.$BASE")
  CUSTOMER_DOMAIN=$(ask "  Customer site"  "$BASE")
  ADMIN_DOMAIN=$(ask "  Admin console"     "admin.$BASE")
  SECRET="$(head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 40)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by go-live-staging.sh — staging only. Do not commit.
API_DOMAIN=$API_DOMAIN
CUSTOMER_DOMAIN=$CUSTOMER_DOMAIN
ADMIN_DOMAIN=$ADMIN_DOMAIN
TUNAKULA_TOKEN_SECRET=$SECRET
EOF
  echo "    Wrote $ENV_FILE"
fi
# shellcheck disable=SC1090
source "$ENV_FILE"

cat <<EOF

    Before continuing, confirm these DNS A records exist and point at this server:
      $API_DOMAIN       → this server
      $CUSTOMER_DOMAIN  → this server
      $ADMIN_DOMAIN     → this server
    (Caddy needs them resolving to issue HTTPS certificates.)
EOF
read -rp "    DNS is set and you're ready to build? [y/N] " go
[[ "$go" =~ ^[Yy]$ ]] || { echo "Stopped. Set DNS, then re-run the same command."; exit 0; }

# 3. Build + start -----------------------------------------------------------
say "Building and starting the platform (first build takes a few minutes)…"
$COMPOSE up -d --build

# 4. Wait for the API to be healthy -----------------------------------------
say "Waiting for the API to migrate and come up…"
for i in $(seq 1 60); do
  if $COMPOSE exec -T api node -e "fetch('http://127.0.0.1:8080/v1/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then
    echo "    API is healthy."; break
  fi
  [[ $i -eq 60 ]] && { echo "API did not become healthy. Check: $COMPOSE logs api"; exit 1; }
  sleep 3
done

# 5. First Super Admin -------------------------------------------------------
say "Create your first Super Admin (you'll sign in with this phone number)."
PHONE=$(ask "  Admin phone in full international form (e.g. +243810000000)")
NAME=$(ask  "  Admin display name" "Launch Owner")
$COMPOSE exec -T api npm run bootstrap-admin -w @tunakula/api -- "$PHONE" "$NAME"

# 6. Done --------------------------------------------------------------------
cat <<EOF

\033[1;32m✔ Tunakula is live (staging).\033[0m

  Customer site : https://$CUSTOMER_DOMAIN
  Admin console : https://$ADMIN_DOMAIN
  API health    : https://$API_DOMAIN/v1/health

  Sign in to the admin console with $PHONE. Because this is staging, your
  sign-in CODE is printed in the API log instead of sent by SMS. Read it with:

      $COMPOSE logs api | grep -i otp

  Next, in the admin console: publish your first market (Country Profile), then
  open the customer site and place a test order (payments are in sandbox mode).

  To see logs:     $COMPOSE logs -f
  To stop:         $COMPOSE down         (add -v to also wipe the database)
EOF
