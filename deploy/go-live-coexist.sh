#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Tunakula — ONE-COMMAND go-live on a VPS that ALREADY runs other sites behind Caddy.
#
# Run this ON THE VPS, from the repo root:
#     bash deploy/go-live-coexist.sh
#
# Unlike go-live-staging.sh (which runs its own Caddy on 80/443 and would collide with your
# existing sites), this uses the COEXIST stack: the API and both sites bind to 127.0.0.1 on
# high ports and join your existing Caddy's Docker network by name, so your current sites are
# untouched and nothing new grabs 80/443. It then wires three subdomains into your existing
# Caddyfile — with a backup, a config validation, and an automatic revert if validation fails.
#
# Safe to re-run: it reuses deploy/.env.staging and never duplicates Caddy blocks.
#
# Override the two site-specific values if your box differs from the defaults:
#     CADDYFILE=/root/koda/app/Caddyfile CADDY_CONTAINER=app-caddy-1 EDGE_NETWORK=construx-edge \
#       bash deploy/go-live-coexist.sh
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
cd "$(dirname "$0")/.."                                   # repo root

ENV_FILE="deploy/.env.staging"
EDGE_NETWORK="${EDGE_NETWORK:-construx-edge}"
CADDYFILE="${CADDYFILE:-/root/koda/app/Caddyfile}"
CADDY_CONTAINER="${CADDY_CONTAINER:-app-caddy-1}"
COMPOSE="docker compose --env-file $ENV_FILE -f deploy/docker-compose.coexist.yml"

say()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m!! %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m✔ %s\033[0m\n' "$*"; }
ask()  { local p="$1" d="${2:-}" a; read -rp "$p${d:+ [$d]}: " a; echo "${a:-$d}"; }

# 1. Prerequisites -----------------------------------------------------------
command -v docker >/dev/null 2>&1 || { echo "Docker is not installed. Install it and re-run."; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose plugin missing."; exit 1; }
docker network inspect "$EDGE_NETWORK" >/dev/null 2>&1 || {
  echo "The edge network '$EDGE_NETWORK' does not exist. This must be the Docker network your existing"
  echo "Caddy shares with its apps. List networks with:  docker network ls"
  echo "Then re-run with:  EDGE_NETWORK=<name> bash deploy/go-live-coexist.sh"
  exit 1
}

# 2. Settings (first run only) ----------------------------------------------
if [[ -f "$ENV_FILE" ]]; then
  say "Using existing $ENV_FILE"
else
  say "First run — set the three domains (DNS A records must already point at this server)."
  # Defaults target the new platform on the tunakula.com apex, beside the old system on cd./drc.
  BASE=$(ask "Your domain" "tunakula.com")
  API_DOMAIN=$(ask "  API subdomain"     "api.$BASE")
  CUSTOMER_DOMAIN=$(ask "  Customer site" "$BASE")
  ADMIN_DOMAIN=$(ask "  Admin console"    "admin.$BASE")
  SECRET="$(head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 40)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by go-live-coexist.sh. Do not commit.
API_DOMAIN=$API_DOMAIN
CUSTOMER_DOMAIN=$CUSTOMER_DOMAIN
ADMIN_DOMAIN=$ADMIN_DOMAIN
EDGE_NETWORK=$EDGE_NETWORK
TUNAKULA_TOKEN_SECRET=$SECRET
EOF
  ok "Wrote $ENV_FILE"
fi
# shellcheck disable=SC1090
source "$ENV_FILE"

# 3. Build + start (localhost only; never 80/443) ----------------------------
say "Building and starting the coexist stack (first build takes a few minutes)…"
$COMPOSE up -d --build

# 4. Wait for the API to migrate and come up ---------------------------------
say "Waiting for the API…"
for i in $(seq 1 60); do
  if $COMPOSE exec -T api node -e "fetch('http://127.0.0.1:8080/v1/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then
    ok "API is healthy (127.0.0.1:8190)."; break
  fi
  [[ $i -eq 60 ]] && { echo "API did not become healthy. Check: $COMPOSE logs api"; exit 1; }
  sleep 3
done

# 5. Wire the three subdomains into the existing Caddyfile -------------------
say "Wiring Caddy ($CADDYFILE via container $CADDY_CONTAINER)…"
if [[ ! -f "$CADDYFILE" ]]; then
  warn "Caddyfile not found at $CADDYFILE — skipping the automatic wiring."
  warn "Add these three blocks to your Caddy config yourself, then reload Caddy:"
  cat <<EOF

$API_DOMAIN {
    reverse_proxy tunakula-api:8080
}
$CUSTOMER_DOMAIN {
    reverse_proxy tunakula-web:80
}
$ADMIN_DOMAIN {
    reverse_proxy tunakula-admin:80
}
EOF
else
  MARKER="# >>> tunakula (managed by go-live-coexist.sh) >>>"
  END_MARKER="# <<< tunakula <<<"

  # Each subdomain and the container it must reach. We verify EACH route independently and add only the
  # ones that are missing — so a re-run repairs a partial earlier setup (e.g. the common case where the API
  # and customer site got wired but admin did not, leaving admin.<domain> showing some other/old page).
  declare -A UPSTREAM=( ["$API_DOMAIN"]="tunakula-api:8080" ["$CUSTOMER_DOMAIN"]="tunakula-web:80" ["$ADMIN_DOMAIN"]="tunakula-admin:80" )

  # Is this exact domain already used as a site address anywhere in the Caddyfile? (Start of a line, optionally
  # with other addresses, before the opening brace — Caddy's "site address {" form.)
  domain_routed() { grep -Eq "(^|[[:space:],])$(printf '%s' "$1" | sed 's/[.]/\\./g')([[:space:],{]|$)" "$CADDYFILE"; }
  # Does OUR managed block already carry a route for this domain?
  in_managed_block() { sed -n "/$MARKER/,/$END_MARKER/p" "$CADDYFILE" 2>/dev/null | grep -Eq "(^|[[:space:],])$(printf '%s' "$1" | sed 's/[.]/\\./g')([[:space:],{]|$)"; }

  MISSING=()        # domains with no route at all → we will add them
  FOREIGN=()        # domains routed OUTSIDE our block → a different/old block owns them; we must not duplicate
  for d in "$API_DOMAIN" "$CUSTOMER_DOMAIN" "$ADMIN_DOMAIN"; do
    if in_managed_block "$d"; then
      :                                   # already ours — fine
    elif domain_routed "$d"; then
      FOREIGN+=("$d")
    else
      MISSING+=("$d")
    fi
  done

  if [[ ${#FOREIGN[@]} -gt 0 ]]; then
    warn "These domains are already routed by ANOTHER block in $CADDYFILE (an old/leftover site):"
    for d in "${FOREIGN[@]}"; do warn "    $d  → should be  reverse_proxy ${UPSTREAM[$d]}"; done
    warn "That foreign block is why $d may show an old/placeholder page instead of Tunakula."
    warn "Remove those domains' existing block(s) from $CADDYFILE, then re-run this script so it can wire them."
  fi

  if [[ ${#MISSING[@]} -eq 0 ]]; then
    [[ ${#FOREIGN[@]} -eq 0 ]] && ok "All three Tunakula routes are already present in $CADDYFILE."
  else
    BACKUP="$CADDYFILE.bak.$(date +%Y%m%d%H%M%S)"
    cp "$CADDYFILE" "$BACKUP"
    ok "Backed up Caddyfile → $BACKUP"
    # Append the missing routes inside the managed markers (create the markers on first use).
    grep -qF "$MARKER" "$CADDYFILE" || printf '\n%s\n%s\n' "$MARKER" "$END_MARKER" >> "$CADDYFILE"
    BLOCKS=""
    for d in "${MISSING[@]}"; do BLOCKS+="$d {
    reverse_proxy ${UPSTREAM[$d]}
}
"; done
    # Insert the new blocks just before the end marker (portable awk, no in-place sed dependency).
    awk -v end="$END_MARKER" -v blocks="$BLOCKS" '$0==end && !done {printf "%s", blocks; done=1} {print}' "$CADDYFILE" > "$CADDYFILE.tmp" && mv "$CADDYFILE.tmp" "$CADDYFILE"
    say "Adding ${#MISSING[@]} missing route(s): ${MISSING[*]}"
    # Validate inside the running Caddy container; revert on failure so the box is never left broken.
    if docker exec "$CADDY_CONTAINER" caddy validate --config /etc/caddy/Caddyfile >/dev/null 2>&1 \
       || docker exec "$CADDY_CONTAINER" caddy validate --config "$CADDYFILE" >/dev/null 2>&1; then
      docker exec "$CADDY_CONTAINER" caddy reload --config /etc/caddy/Caddyfile 2>/dev/null \
        || docker exec "$CADDY_CONTAINER" caddy reload --config "$CADDYFILE" 2>/dev/null \
        || docker restart "$CADDY_CONTAINER" >/dev/null
      ok "Caddy reloaded with the Tunakula route(s)."
    else
      warn "Caddy rejected the new config — reverting and leaving your sites untouched."
      cp "$BACKUP" "$CADDYFILE"
      warn "The route(s) below need adjusting for your Caddyfile's format:"
      printf '%s' "$BLOCKS"
      exit 1
    fi
  fi
fi

# 6. First Super Admin -------------------------------------------------------
say "Create your first Super Admin (sign in with this phone number)."
PHONE=$(ask "  Admin phone in full international form (e.g. +243810000000)")
NAME=$(ask  "  Admin display name" "Launch Owner")
$COMPOSE exec -T api npm run bootstrap-admin -w @tunakula/api -- "$PHONE" "$NAME"

# 6b. Publish the DRC market as a PILOT PLACEHOLDER so the storefront serves a market instead of falling back to
# its built-in preview. Idempotent (skips if already published) and seeds NO sample data — only the market itself.
# --starter acknowledges this is a placeholder with machine-signed readiness; the owner MUST complete the real
# company/legal/payment/zone details, re-sign readiness, and move the market to LIVE in admin → Markets before
# taking real money.
say "Publishing the DRC (CD) market as a PILOT placeholder…"
$COMPOSE exec -T api npm run publish-market -w @tunakula/api -- CD --starter || warn "Market publish skipped/failed — publish it from the admin Markets console instead."

# 7. Done --------------------------------------------------------------------
cat <<EOF

$(ok "Tunakula is live alongside your other sites.")

  Customer site : https://$CUSTOMER_DOMAIN
  Admin console : https://$ADMIN_DOMAIN
  API health    : https://$API_DOMAIN/v1/health

  Sign in to the admin console with $PHONE. Staging prints the sign-in CODE to the
  API log instead of SMS — read it with:
      $COMPOSE logs api | grep -i otp | tail -1

  Then: publish your first market (Country Profile), and point the apps' API URL at
  https://$API_DOMAIN (apps/*/app.json → expo.extra.apiUrl) before building them on EAS.

  Logs:  $COMPOSE logs -f        Stop:  $COMPOSE down   (keeps the database)
EOF
